// variants with their stages, and everything that has to list them.
// Usage: node tools/generate-firms.mjs [gameDir]
//
// Jobs: copied from the vanilla job's resources (same outputs, inputs and job swaps
// such as Catalytic Processing), but in an own economic category whose parent is the
// vanilla one, so all technology and other bonuses still apply.
