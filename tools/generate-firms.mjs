// Generates the firm variants and everything that has to list them.
// Usage: node tools/generate-firms.mjs
//
// A firm has 3 shares. Urban firms (one city district slot): any mix of alloys,
// consumer goods and trade, 40 workforce per share. Rural firms (one slot plus one
// district of their primary type): at least 2 shares of the primary resource, the
// third share free, 80 workforce per rural share and 40 per urban share.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const write = (file, text) => { fs.mkdirSync(path.dirname(path.join(root, file)), {recursive: true}); fs.writeFileSync(path.join(root, file), text); };
const header = '# Generated by tools/generate-firms.mjs - do not edit by hand.\n';

const P = {
  a: {res: 'alloys', job: 'pe_private_metallurgist', urban: true, en: 'Steelworks', de: 'Stahlwerk', enDiv: 'Steel', deDiv: 'Stahl', enArt: 'Private Steelworks', deArt: 'Privates Stahlwerk'},
  c: {res: 'consumer_goods', job: 'pe_private_artisan', urban: true, enArt: 'Private Factory', deArt: 'Private Fabrik', enDiv: 'Goods', deDiv: 'Konsumgüter'},
  t: {res: 'trade', job: 'pe_private_trader', urban: true, enArt: 'Private Trading House', deArt: 'Privates Handelshaus', enDiv: 'Trade', deDiv: 'Handels'},
  m: {res: 'minerals', job: 'pe_private_miner', district: 'district_mining', icon: 'd_mineral_fields', enArt: 'Private Mine', deArt: 'Private Mine', enDiv: 'Mining', deDiv: 'Bergbau', enDist: 'mining', deDist: 'Bergbau'},
  e: {res: 'energy', job: 'pe_private_technician', district: 'district_generator', icon: 'd_geothermal_vent', enArt: 'Private Power Plant', deArt: 'Privates Kraftwerk', enDiv: 'Energy', deDiv: 'Energie', enDist: 'generator', deDist: 'Generator'},
  f: {res: 'food', job: 'pe_private_farmer', district: 'district_farming', icon: 'd_fertile_lands', enArt: 'Private Farm', deArt: 'Privater Agrarbetrieb', enDiv: 'Agricultural', deDiv: 'Agrar', enDist: 'farming', deDist: 'Landwirtschafts'},
};
const urban = ['a', 'c', 't'], rural = ['m', 'e', 'f'];
const WEIGHTS = [1, 0.75, 0.5];            // diminishing value of repeated shares
const COST = {u: 500, r: 300};             // founding, paid from private capital
const PRICE = {u: [500, 100], r: [300, 60]}; // buyout / nationalisation: minerals, trade
const UPKEEP = {u: 2, r: 1};               // energy, like the matching district

// Variants: key letters sorted with the primary first.
const variants = [];
for (let i = 0; i < 3; i++) for (let j = i; j < 3; j++) for (let k = j; k < 3; k++) {
  const s = [urban[i], urban[j], urban[k]];
  const counts = {}; for (const x of s) counts[x] = (counts[x] || 0) + 1;
  const primary = Object.keys(counts).sort((x, y) => counts[y] - counts[x])[0];
  variants.push({shares: s, counts, primary, cls: 'u'});
}
for (const r of rural) for (const x of [r, ...urban, ...rural.filter(y => y !== r)]) {
  const s = [r, r, x];
  const counts = {}; for (const y of s) counts[y] = (counts[y] || 0) + 1;
  variants.push({shares: s, counts, primary: r, cls: r});
}
variants.forEach((v, i) => {
  v.code = i + 1;
  const side = Object.keys(v.counts).filter(x => x !== v.primary);
  v.side = side.length === 1 && v.counts[v.primary] === 2 ? side[0] : null;
  v.mixedAll = Object.keys(v.counts).length === 3;
  v.key = 'd_pe_firm_' + (v.mixedAll ? v.shares.join('') : v.primary.repeat(v.counts[v.primary]) + (v.side || ''));
  v.urbanCls = v.cls === 'u';
  v.workforce = {};
  for (const [x, n] of Object.entries(v.counts)) v.workforce[P[x].job] = n * (v.urbanCls || P[x].urban ? 40 : 80);
});

// --- Deposits -------------------------------------------------------------------
let dep = header + `# Firm variants: one district slot each (rural ones also one district of their type).
# Placed only by script; cannot be cleared. Energy upkeep like the matching district.
`;
for (const v of variants) {
  const mods = ['planet_max_districts_add = -1'];
  if (!v.urbanCls) mods.push(`${P[v.cls].district}_max_add = -1`);
  for (const [job, wf] of Object.entries(v.workforce)) mods.push(`job_${job}_add = ${wf}`);
  dep += `
${v.key} = {
	icon = ${v.urbanCls ? 'd_city' : P[v.cls].icon}
	is_for_colonizable = yes
	category = pe_deposit_cat_firms
	can_be_cleared = { always = no }
	potential = { always = no }
	drop_weight = { weight = 0 }

	resources = {
		category = planet_deposits
		upkeep = {
			energy = ${UPKEEP[v.urbanCls ? 'u' : 'r']}
		}
	}

	planet_modifier = {
${mods.map(m => '\t\t' + m).join('\n')}
	}
}
`;
}
write('common/deposits/pe_firm_deposits.txt', dep);

// --- Triggers -------------------------------------------------------------------
const sideOk = v => v.side && !P[v.side].urban && !v.urbanCls
  ? ` OR = { has_district = ${P[v.side].district} num_free_districts = { type = ${P[v.side].district} value > 0 } }` : '';
let trg = header + `# Colony scope, per variant: can it be founded on a free slot, bought from the state,
# or chosen by a firm of the same class that restructures? A rural side share needs
# the planet to have that district type at all (its deposits).
`;
for (const v of variants) {
  const s = sideOk(v);
  if (v.urbanCls) {
    trg += `pe_can_found_${v.key} = { free_district_slots > 0 }\n`;
    trg += `pe_can_buy_${v.key} = { has_district = district_city }\n`;
    trg += `pe_can_retool_${v.key} = { always = yes }\n`;
  } else {
    const d = P[v.cls].district;
    trg += `pe_can_found_${v.key} = { free_district_slots > 0 num_free_districts = { type = ${d} value > 0 }${s} }\n`;
    trg += `pe_can_buy_${v.key} = { has_district = ${d}${s} }\n`;
    trg += `pe_can_retool_${v.key} = { always = yes${s} }\n`;
  }
}
write('common/scripted_triggers/pe_firm_triggers_generated.txt', trg);

// --- Effects --------------------------------------------------------------------
const chain = (varName, fn, scopeVar = 'root') => variants.map((v, i) =>
  `\t${i ? 'else_if' : 'if'} = { limit = { ${scopeVar} = { check_variable = { which = ${varName} value = ${v.code} } } } ${fn(v)} }`).join('\n');
const clsKey = v => v.urbanCls ? 'u' : 'r';
const offerClass = v => v.urbanCls ? 1 : rural.indexOf(v.cls) + 2;

let eff = header + `# Call depths (see pe_economy_effects.txt): pe_compute_values 2, pe_choose_variant 3,
# pe_found_variant 3, pe_buy_or_offer 3, pe_nationalise_one 3, pe_restructure 3,
# pe_buyout_by_offer 1 (from pe.110).

# Country scope: value of every variant from the resource scores, with diminishing
# value for repeated shares (${WEIGHTS.join(' / ')}). Also the best urban variant.
pe_compute_values = {
	set_variable = { which = pe_cls_val_u value = -100000 }
	set_variable = { which = pe_cls_var_u value = 0 }
`;
for (const v of variants) {
  let first = true;
  for (const [x, n] of Object.entries(v.counts)) {
    const w = WEIGHTS.slice(0, n).reduce((a, b) => a + b, 0);
    if (first) {
      eff += `\tset_variable = { which = pe_val_${v.key} value = pe_score_${P[x].res} }\n`;
      if (w !== 1) eff += `\tmultiply_variable = { which = pe_val_${v.key} value = ${w} }\n`;
      first = false;
    } else {
      eff += `\tset_variable = { which = pe_tmp value = pe_score_${P[x].res} }\n`;
      if (w !== 1) eff += `\tmultiply_variable = { which = pe_tmp value = ${w} }\n`;
      eff += `\tchange_variable = { which = pe_val_${v.key} value = pe_tmp }\n`;
    }
  }
  if (v.urbanCls) eff += `\tif = { limit = { check_variable = { which = pe_val_${v.key} value > pe_cls_val_u } } set_variable = { which = pe_cls_val_u value = pe_val_${v.key} } set_variable = { which = pe_cls_var_u value = ${v.code} } }\n`;
}
eff += `}

# Colony scope: root.pe_best_variant = most valuable variant available here (0 = none
# worth more than 0).
pe_choose_variant = {
	root = {
		set_variable = { which = pe_best value = 0 }
		set_variable = { which = pe_best_variant value = 0 }
	}
${variants.map(v => `\tpe_consider_variant = { V = ${v.key} CODE = ${v.code} MODE = $MODE$ }`).join('\n')}
}

# Colony scope: found the chosen variant on a free slot.
pe_found_variant = {
${chain('pe_best_variant', v => `pe_found_firm = { FIRM = ${v.key} COST = ${COST[clsKey(v)]} }`)}
}

# Colony scope: buy a state district. Human empires on Free Market get an offer (one per
# quarter); AI empires and Laissez-faire buy directly.
pe_buy_or_offer = {
${chain('pe_best_variant', v => {
  const [m, t] = PRICE[clsKey(v)], d = v.urbanCls ? 'district_city' : P[v.cls].district;
  return `
		if = {
			limit = {
				owner = { is_ai = no has_policy_flag = pe_order_free_market NOT = { has_country_flag = pe_offer_pending } check_variable = { which = pe_capital value >= ${m + t} } }
			}
			set_timed_planet_flag = { flag = pe_cooldown days = 360 }
			save_event_target_as = pe_offer_planet
			root = {
				set_variable = { which = pe_offer_variant value = ${v.code} }
				set_variable = { which = pe_offer_class value = ${offerClass(v)} }
				set_timed_country_flag = { flag = pe_offer_pending days = 90 }
				country_event = { id = pe.110 }
			}
		}
		else_if = {
			limit = { owner = { OR = { is_ai = yes has_policy_flag = pe_order_laissez_faire } } }
			pe_buyout_execute = { FIRM = ${v.key} DISTRICT = ${d} MINERALS = ${m} TRADE = ${t} PRICE = ${m + t} }
		}
	`;
})}
}

# Event pe.110 scope (country), colony = event_target:pe_offer_planet.
pe_buyout_by_offer = {
${chain('pe_offer_variant', v => {
  const [m, t] = PRICE[clsKey(v)], d = v.urbanCls ? 'district_city' : P[v.cls].district;
  return `pe_buyout_execute = { FIRM = ${v.key} DISTRICT = ${d} MINERALS = ${m} TRADE = ${t} PRICE = ${m + t} }`;
}, 'owner')}
}

# Colony scope: the state buys back the least valuable firm.
pe_nationalise_one = {
	root = {
		set_variable = { which = pe_worst value = 100000 }
		set_variable = { which = pe_worst_variant value = 0 }
	}
${variants.map(v => `\tpe_nat_consider = { V = ${v.key} CODE = ${v.code} }`).join('\n')}
${chain('pe_worst_variant', v => {
  const [m, t] = PRICE[clsKey(v)], d = v.urbanCls ? 'district_city' : P[v.cls].district;
  return `pe_nationalise_firm = { FIRM = ${v.key} DISTRICT = ${d} MINERALS = ${m} TRADE = ${t} PRICE = ${m + t} }`;
})}
}

# Colony scope: the firm with the largest gain switches to the best variant of its
# class (same footprint), if the gain is at least 40 and capital covers half the
# founding cost.
pe_restructure = {
	root = {
		set_variable = { which = pe_retool_ok value = 0 }
		set_variable = { which = pe_best_gain value = 39.99 }
		set_variable = { which = pe_from value = 0 }
		set_variable = { which = pe_to value = 0 }
${rural.map(r => `\t\tset_variable = { which = pe_cls_val_${r} value = -100000 }\n\t\tset_variable = { which = pe_cls_var_${r} value = 0 }`).join('\n')}
	}
${variants.filter(v => !v.urbanCls).map(v => `\tpe_retool_consider = { V = ${v.key} CODE = ${v.code} CLS = ${v.cls} }`).join('\n')}
${variants.map(v => `\tpe_retool_gain = { V = ${v.key} CODE = ${v.code} CLS = ${v.urbanCls ? 'u' : v.cls} }`).join('\n')}
${chain('pe_from', v => `if = { limit = { owner = { check_variable = { which = pe_capital value >= ${COST[clsKey(v)] / 2} } } } remove_deposit = ${v.key} owner = { change_variable = { which = pe_capital value = -${COST[clsKey(v)] / 2} } } root = { set_variable = { which = pe_retool_ok value = 1 } } }`)}
	if = {
		limit = { root = { check_variable = { which = pe_retool_ok value = 1 } } }
		set_timed_planet_flag = { flag = pe_cooldown days = 360 }
		save_event_target_as = pe_msg_planet
	${chain('pe_to', v => `add_deposit = ${v.key} owner = { create_message = { type = pe_private_economy localization = pe_msg_retool_${v.key} days = 30 target = event_target:pe_msg_planet variable = { type = name localization = PLANET scope = event_target:pe_msg_planet } } }`).replaceAll('\n', '\n\t')}
	}
}
`;
write('common/scripted_effects/pe_firm_effects_generated.txt', eff);

// --- Scripted localisation (country scope) --------------------------------------
const dtext = (name, varName, entries, fallback) => `defined_text = {
	name = ${name}
${entries.map(([val, key]) => `	text = {
		trigger = { check_variable = { which = ${varName} value = ${val} } }
		localization_key = ${key}
	}`).join('\n')}
	default = ${fallback}
}
`;
write('common/scripted_loc/pe_scripted_loc_generated.txt', header +
  dtext('GetPeBestFirm', 'pe_best_variant', variants.map(v => [v.code, v.key]), 'pe_no_firm') + '\n' +
  dtext('GetPeOfferFirm', 'pe_offer_variant', variants.map(v => [v.code, v.key]), 'pe_no_firm') + '\n' +
  dtext('GetPeOfferDistrict', 'pe_offer_class', [[1, 'pe_dist_city'], [2, 'pe_dist_mining'], [3, 'pe_dist_generator'], [4, 'pe_dist_farming']], 'pe_dist_city'));

// --- Localisation -------------------------------------------------------------------
const nameOf = (v, lang) => {
  const L = lang === 'en';
  if (v.mixedAll) return L ? 'Private Conglomerate' : 'Privater Mischkonzern';
  const base = P[v.primary][L ? 'enArt' : 'deArt'];
  if (!v.side) return base;
  return L ? `${base} with ${P[v.side].enDiv} Division` : `${base} mit ${P[v.side].deDiv}sparte`;
};
const jobsText = (v, lang) => Object.entries(v.workforce).map(([job, wf]) => `${wf} $job_${job}_plural$`).join(', ');
const loc = {
  english: [
    ' pe_no_firm:0 "none"',
    ' pe_dist_city:0 "city district"', ' pe_dist_mining:0 "mining district"', ' pe_dist_generator:0 "generator district"', ' pe_dist_farming:0 "farming district"',
  ],
  german: [
    ' pe_no_firm:0 "keine"',
    ' pe_dist_city:0 "Stadtdistrikt"', ' pe_dist_mining:0 "Bergbaudistrikt"', ' pe_dist_generator:0 "Generatordistrikt"', ' pe_dist_farming:0 "Landwirtschaftsdistrikt"',
  ],
};
for (const v of variants) {
  const k = clsKey(v), [m, t] = PRICE[k];
  const en = nameOf(v, 'en'), de = nameOf(v, 'de');
  const enDist = v.urbanCls ? 'city' : P[v.cls].enDist, deDist = v.urbanCls ? 'Stadt' : P[v.cls].deDist;
  loc.english.push(
    ` ${v.key}:0 "${en}"`,
    ` ${v.key}_desc:0 "A private company that decides itself what it produces. It occupies a district slot${v.urbanCls ? '' : ` and one ${enDist} district`}. Workforce: ${jobsText(v)}."`,
    ` pe_msg_found_${v.key}:0 "A §Y$${v.key}$§! has opened on $PLANET$."`,
    ` pe_msg_buy_${v.key}:0 "A §Y$${v.key}$§! bought a ${enDist} district on $PLANET$ and paid §G${m}§! £minerals£ and §G${t}§! £trade£."`,
    ` pe_msg_nat_${v.key}:0 "We nationalised a §Y$${v.key}$§! on $PLANET$ for §R${m}§! £minerals£ and §R${t}§! £trade£. It is a ${enDist} district again."`,
    ` pe_msg_retool_${v.key}:0 "A firm on $PLANET$ has restructured into a §Y$${v.key}$§!."`,
  );
  loc.german.push(
    ` ${v.key}:0 "${de}"`,
    ` ${v.key}_desc:0 "Ein privates Unternehmen, das selbst entscheidet, was es produziert. Es belegt einen Distriktplatz${v.urbanCls ? '' : ` und einen ${deDist}distrikt`}. Arbeitskraft: ${jobsText(v)}."`,
    ` pe_msg_found_${v.key}:0 "Auf $PLANET$ wurde ein Unternehmen gegründet: §Y$${v.key}$§!."`,
    ` pe_msg_buy_${v.key}:0 "§Y$${v.key}$§! hat auf $PLANET$ einen ${deDist}distrikt gekauft und §G${m}§! £minerals£ und §G${t}§! £trade£ gezahlt."`,
    ` pe_msg_nat_${v.key}:0 "Wir haben §Y$${v.key}$§! auf $PLANET$ für §R${m}§! £minerals£ und §R${t}§! £trade£ verstaatlicht. Es ist wieder ein ${deDist}distrikt."`,
    ` pe_msg_retool_${v.key}:0 "Ein Unternehmen auf $PLANET$ hat umstrukturiert: jetzt §Y$${v.key}$§!."`,
  );
}
for (const [lang, lines] of Object.entries(loc))
  write(`localisation/${lang}/pe_firms_generated_l_${lang}.yml`, `﻿l_${lang}:\n${lines.join('\n')}\n`);

console.log(`${variants.length} variants: ${variants.map(v => v.key.slice(10)).join(' ')}`);
