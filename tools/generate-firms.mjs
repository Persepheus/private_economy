const blockAt = (text, open) => { let d = 0; for (let j = open; j < text.length; j++) { if (text[j] === '{') d++; else if (text[j] === '}' && --d === 0) return text.slice(open, j + 1); } throw new Error('unbalanced'); };
const topDef = (texts, key) => { for (const t of texts) { const i = t.search(new RegExp(`^${key} = \\{`, 'm')); if (i >= 0) return blockAt(t, t.indexOf('{', i)); } throw new Error(`no ${key}`); };

